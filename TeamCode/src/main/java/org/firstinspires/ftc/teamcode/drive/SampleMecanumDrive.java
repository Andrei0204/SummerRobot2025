    public void turnAsync(double angle) {
        trajectorySequenceRunner.followTrajectorySequenceAsync(
                trajectorySequenceBuilder(getPoseEstimate())
                        .turn(angle)
                        .build()
        );
    }

    public void setXY(Pose2dM pose, double slowTurn, boolean slowBack, boolean slowForward){
        double y = pose.y, x = -pose.x, rot = pose.heading;

        if(slowBack) y = -0.2;
        if(slowForward) y = 0.2;

        if(Math.abs(slowTurn) > 0.05){
            x = 0.4 * (slowTurn / Math.abs(slowTurn));
        }

        rightFront.setPower(y-x-rot);
        leftFront.setPower(y+x+rot);
        rightRear.setPower(y+x-rot);
        leftRear.setPower(y-x+rot);
    }
    public void set(Pose2dM pose, double maxPower) { // mainDrive
        double x = pose.x, y = pose.y, rot = pose.heading;

        double speed = Math.hypot(x, y);

        double robotAngle = Math.atan2(y, x) - Math.PI / 4;

        double power = 0.6;
        double rotPower = 1;

        if(maxPower >= 0.05){
            if(Math.abs(speed) > 0.9 && power < 1.5){
                double delta = Math.abs(speed) * 0.02;
                power = power + delta;
            }else if(Math.abs(speed)<0.6){
                power = 0.6;
            }
        }
        else power = 1;

        double FLPower = (speed * Math.sin(robotAngle)) * power + rot;
        double FRPower = (speed * Math.cos(robotAngle)) * power - rot;
        double BLPower = (speed * Math.cos(robotAngle)) * power + rot;
        double BRPower = (speed * Math.sin(robotAngle)) * power - rot;

        double[] Powers = {FLPower, FRPower, BLPower, BRPower};

        Arrays.sort(Powers);

        if (FLPower > 1 && FRPower > 1 && BLPower > 1 && BRPower > 1) {
            FLPower = FLPower / Powers[3];
            FRPower = FRPower / Powers[3];
            BLPower = BLPower / Powers[3];
            BRPower = BRPower / Powers[3];
        }

        leftFront.setPower(FLPower);
        rightFront.setPower(FRPower);
        leftRear.setPower(BLPower);
        rightRear.setPower(BRPower);
    }

    public void turn(double angle) {
        turnAsync(angle);
        waitForIdle();
    }

    public void followTrajectoryAsync(Trajectory trajectory) {
        trajectorySequenceRunner.followTrajectorySequenceAsync(
                trajectorySequenceBuilder(trajectory.start())
                        .addTrajectory(trajectory)
                        .build()
        );
    }

    public void followTrajectory(Trajectory trajectory) {
        followTrajectoryAsync(trajectory);
        waitForIdle();
    }

    public void followTrajectorySequenceAsync(TrajectorySequence trajectorySequence) {
        trajectorySequenceRunner.followTrajectorySequenceAsync(trajectorySequence);
    }

    public void followTrajectorySequence(TrajectorySequence trajectorySequence) {
        followTrajectorySequenceAsync(trajectorySequence);
        waitForIdle();
    }

    public Pose2d getLastError() {
        return trajectorySequenceRunner.getLastPoseError();
    }

    public void update() {
        updatePoseEstimate();
        DriveSignal signal = trajectorySequenceRunner.update(getPoseEstimate(), getPoseVelocity());
        if (signal != null) setDriveSignal(signal);
    }

    public void update(Pose2d Pose,Pose2d Velocity) {
        DriveSignal signal = trajectorySequenceRunner.update(new Pose2d(Pose.getX(),Pose.getY(),Pose.getHeading()), Velocity);
        if (signal != null) setDriveSignal(signal);
    }

    public void waitForIdle() {
        while (!Thread.currentThread().isInterrupted() && isBusy())
            update();
    }

    public boolean isBusy() {
        return trajectorySequenceRunner.isBusy();
    }

    public void setMode(DcMotor.RunMode runMode) {
        for (DcMotorEx motor : motors) {
            motor.setMode(runMode);
        }
    }

    public void setZeroPowerBehavior(DcMotor.ZeroPowerBehavior zeroPowerBehavior) {
        for (DcMotorEx motor : motors) {
            motor.setZeroPowerBehavior(zeroPowerBehavior);
        }
    }

    public void setPIDFCoefficients(DcMotor.RunMode runMode, PIDFCoefficients coefficients) {
        PIDFCoefficients compensatedCoefficients = new PIDFCoefficients(
                coefficients.p, coefficients.i, coefficients.d,
                coefficients.f * 12 / batteryVoltageSensor.getVoltage()
        );

        for (DcMotorEx motor : motors) {
            motor.setPIDFCoefficients(runMode, compensatedCoefficients);
        }
    }

    public void setWeightedDrivePower(Pose2d drivePower) {
        Pose2d vel = drivePower;

        if (Math.abs(drivePower.getX()) + Math.abs(drivePower.getY())
                + Math.abs(drivePower.getHeading()) > 1) {
            // re-normalize the powers according to the weights
            double denom = VX_WEIGHT * Math.abs(drivePower.getX())
                    + VY_WEIGHT * Math.abs(drivePower.getY())
                    + OMEGA_WEIGHT * Math.abs(drivePower.getHeading());

            vel = new Pose2d(
                    VX_WEIGHT * drivePower.getX(),
                    VY_WEIGHT * drivePower.getY(),
                    OMEGA_WEIGHT * drivePower.getHeading()
            ).div(denom);
        }

        setDrivePower(vel);
    }

    @NonNull
    @Override
    public List<Double> getWheelPositions() {
        lastEncPositions.clear();

        List<Double> wheelPositions = new ArrayList<>();
        for (DcMotorEx motor : motors) {
            int position = motor.getCurrentPosition();
            lastEncPositions.add(position);
            wheelPositions.add(encoderTicksToInches(position));
        }
        return wheelPositions;
    }

    @Override
    public List<Double> getWheelVelocities() {
        lastEncVels.clear();

        List<Double> wheelVelocities = new ArrayList<>();
        for (DcMotorEx motor : motors) {
            int vel = (int) motor.getVelocity();
            lastEncVels.add(vel);
            wheelVelocities.add(encoderTicksToInches(vel));
        }
        return wheelVelocities;
    }

    public void setAllMotors(double power){
        setMotorPowers(power, power, power, power);
    }

    public void stopMotors(){
        setAllMotors(0);
    }

    @Override
    public void setMotorPowers(double v, double v1, double v2, double v3) {
        leftFront.setPower(v);
        leftRear.setPower(v1);
        rightRear.setPower(v2);
        rightFront.setPower(v3);
    }

    @Override
    public double getRawExternalHeading() {
        return imu.getHeading();
    }

    @Override
    public Double getExternalHeadingVelocity() {
        return (double) imu.getVelocity();
    }




    public static TrajectoryVelocityConstraint getVelocityConstraint(double maxVel, double maxAngularVel, double trackWidth) {
        return new MinVelocityConstraint(Arrays.asList(
                new AngularVelocityConstraint(maxAngularVel),
                new MecanumVelocityConstraint(maxVel, trackWidth)
        ));
    }

    public static TrajectoryAccelerationConstraint getAccelerationConstraint(double maxAccel) {
        return new ProfileAccelerationConstraint(maxAccel);
    }
